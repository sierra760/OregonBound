/// Complete resource identities for the supported Macintosh 1.1 and CD 1.2
/// source forks. These are type/ID inventories, not game payloads. Validation
/// runs before decoding so an anchor match cannot hide a missing companion part.
enum GameSourceRequirements {
    enum Failure: Error, CustomStringConvertible {
        case inventory(GameDataSourceRole, missing: [String], unexpected: [String])
        case duplicate(GameDataSourceRole, String, Int)
        var description: String {
            switch self {
            case .inventory(let role, let missing, let unexpected):
                return "Unsupported or incomplete \(role.title). Missing resources: \(missing.joined(separator: ", ")); unexpected resources: \(unexpected.joined(separator: ", "))."
            case .duplicate(let role, let type, let id): return "Duplicate resource \(type) \(id) in \(role.title)."
            }
        }
    }

    static func validate(_ selection: GameDataSourceCatalog.Selection) throws {
        for role in selection.edition.requiredRoles {
            guard let candidate = selection.sources[role] else { throw GameDataSourceCatalog.Failure.missing([role]) }
            try validate(candidate.fork, role: role, required: resources(for: role))
        }
    }

    static func validate(_ fork: MacResourceFork, role: GameDataSourceRole, required: [String: Set<Int>]) throws {
        typealias Identity = GameDataSourceCatalog.ResourceIdentity
        var actual: Set<Identity> = []
        for resource in fork.resources {
            guard actual.insert(Identity(type: resource.type, id: resource.id)).inserted else {
                throw Failure.duplicate(role, resource.type, resource.id)
            }
        }
        let expected = Set(required.flatMap { type, ids in ids.map { Identity(type: type, id: $0) } })
        func describe(_ values: Set<Identity>) -> [String] {
            values.sorted { ($0.type, $0.id) < ($1.type, $1.id) }.map { "\($0.type) \($0.id)" }
        }
        guard actual == expected else {
            throw Failure.inventory(role, missing: describe(expected.subtracting(actual)), unexpected: describe(actual.subtracting(expected)))
        }
    }

